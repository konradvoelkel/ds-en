#!/bin/bash
# Build the book and publish it to GitHub Pages.
#
#     tools/deploy-pages.sh
#
# The site is served from https://konradvoelkel.github.io/ds-en/, so it has to be built
# with BASE_URL=/ds-en -- without that every asset path points at the domain root and the
# published site loads nothing.
#
# The built site goes to the `gh-pages` branch as a single commit, force-pushed. That
# branch is output, never source: it carries no history on purpose, so that 119 MB of
# generated HTML does not accumulate in the repository one deploy at a time.
#
# This script exists because the better route is blocked: a GitHub Actions workflow would
# deploy from an artifact and never put the site in git at all, but pushing a workflow
# file needs a token with the `workflow` scope. Once that is granted
# (`gh auth refresh -h github.com -s workflow`), prefer .github/workflows/ and delete
# both this script and the gh-pages branch.
set -euo pipefail

REPO_URL="https://github.com/konradvoelkel/ds-en.git"
BASE="/ds-en"
root="$(cd "$(dirname "$0")/.." && pwd)"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

cd "$root"
echo "building with BASE_URL=$BASE ..."
rm -rf _build
BASE_URL="$BASE" myst build --html

# A stale _build is how four copies of the same PDF ended up in one site; hence the rm.
test -f _build/html/index.html || { echo "no index.html — build failed"; exit 1; }
grep -q "$BASE/build/" _build/html/index.html || {
    echo "assets are not prefixed with $BASE — refusing to publish a site that loads nothing"
    exit 1
}

cp -r _build/html/. "$work"/
touch "$work/.nojekyll"   # keep Pages from running Jekyll over the output

cd "$work"
git init -q -b gh-pages
git add -A
git commit -q -m "Built site for GitHub Pages

Generated by \`BASE_URL=$BASE myst build --html\` from ds-en main at $(git -C "$root" rev-parse --short HEAD)."
git remote add origin "$REPO_URL"
git push -q --force origin gh-pages

echo "published: https://konradvoelkel.github.io/ds-en/"
echo "Pages takes a few minutes to rebuild; check with:"
echo "  gh api repos/konradvoelkel/ds-en/pages --jq .status"
